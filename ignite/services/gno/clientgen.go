package gno

import (
	"fmt"
	"strings"
)

// realmClientTmpl is the fixed prelude of generated typed realm clients.
// The generated module follows the GnoWallet.addRealm pattern of
// @gnolang/gno-js-client.
const realmClientTmpl = `// Code generated by ignite. DO NOT EDIT.
// Typed realm client for %s, built on @gnolang/gno-js-client.

import {
  GnoWallet,
  parseGnoReturns,
} from "@gnolang/gno-js-client";

const pkgPath = %q;

export interface %sRealm {
%s}

/**
 * %sRealm attaches the typed methods of %s to a GnoWallet.
 * Use with GnoWallet.addRealm(%sRealm).
 */
export const %sRealm = (instance: GnoWallet): { realm: %sRealm } => ({
  realm: {
%s
  },
});

// Usage:
//   const Wallet = GnoWallet.addRealm(%sRealm);
//   const wallet = await Wallet.fromMnemonic(mnemonic);
//   await wallet.getProvider()?.connect?.();
//   await wallet.realm.%s();
`

// GenerateRealmClient renders a typed realm module for the package
// signatures, in the GnoWallet.addRealm shape of @gnolang/gno-js-client.
// Read-only functions evaluate expressions through the wallet's provider;
// realm methods broadcast MsgCall transactions with wallet.callMethod.
func GenerateRealmClient(sig *PackageSignatures) string {
	iface := renderRealmIface(sig)
	methods := renderRealmMethods(sig)

	return fmt.Sprintf(realmClientTmpl,
		sig.PkgPath,            // header comment
		sig.PkgPath,            // pkgPath const
		tsPascal(sig.Name),     // interface name
		iface,                  // interface body
		tsPascal(sig.Name),     // doc: factory name
		sig.PkgPath,            // doc: pkg path
		tsPascal(sig.Name),     // doc: addRealm arg
		tsCamel(sig.Name),      // factory name
		tsPascal(sig.Name),     // factory return type
		methods,                // methods body
		tsCamel(sig.Name),      // usage: addRealm
		firstMethodSample(sig), // usage: example call
	)
}

// renderRealmIface renders the TypeScript interface members.
func renderRealmIface(sig *PackageSignatures) string {
	var b strings.Builder
	for _, fn := range sig.Funcs {
		params := tsParams(fn)
		ret := "Promise<any>"
		if !fn.Realm {
			ret = "Promise<Array<unknown>>"
		}
		comment := "read-only expression evaluated on-chain"
		if fn.Realm {
			comment = "realm method (mutates on-chain state)"
		}
		fmt.Fprintf(&b, "  // %s is a %s.\n  %s(%s): %s;\n", fn.Name, comment, tsCamel(fn.Name), strings.Join(params, ", "), ret)
	}
	return b.String()
}

// renderRealmMethods renders the realm object method implementations.
func renderRealmMethods(sig *PackageSignatures) string {
	var b strings.Builder
	for _, fn := range sig.Funcs {
		callArgs := make([]string, 0, len(fn.Args))
		for _, arg := range fn.Args {
			callArgs = append(callArgs, "String("+tsCamel(arg.Name)+")")
		}

		if fn.Realm {
			fmt.Fprintf(&b, `    async %s(send?: Map<string, number>): Promise<any> {
      return instance.callMethod(pkgPath, %q, [%s], "commit", send);
    },
`, tsCamel(fn.Name), fn.Name, strings.Join(callArgs, ", "))
			continue
		}

		evalArgs := make([]string, 0, len(fn.Args))
		for _, arg := range fn.Args {
			evalArgs = append(evalArgs, fmt.Sprintf("JSON.stringify(String(%s))", tsCamel(arg.Name)))
		}
		fmt.Fprintf(&b, `    async %s(%s): Promise<Array<unknown>> {
      const provider = instance.getProvider();
      if (!provider) {
        throw new Error("the wallet has no connected provider");
      }
      const res = await provider.evaluateExpression(pkgPath, %q + "(" + [%s].join(", ") + ")");
      return parseGnoReturns(res);
    },
`, tsCamel(fn.Name), strings.Join(tsParams(fn), ", "), fn.Name, strings.Join(evalArgs, ", "))
	}
	return b.String()
}

// tsParams renders the TypeScript parameters of a function.
func tsParams(fn FuncSig) []string {
	params := make([]string, 0, len(fn.Args))
	for _, arg := range fn.Args {
		params = append(params, fmt.Sprintf("%s: %s", tsCamel(arg.Name), tsType(arg.Type)))
	}
	return params
}

// firstMethodSample returns the first method name for the usage snippet.
func firstMethodSample(sig *PackageSignatures) string {
	if len(sig.Funcs) == 0 {
		return "noop"
	}
	return tsCamel(sig.Funcs[0].Name)
}

// tsType maps a gno type to a TypeScript type.
func tsType(gnoType string) string {
	switch gnoType {
	case "string":
		return "string"
	case "int", "int8", "int16", "int32", "int64", "uint", "uint8", "uint16",
		"uint32", "uint64", "float32", "float64", "byte", "rune":
		return "number"
	case "bool":
		return "boolean"
	default:
		if strings.HasPrefix(gnoType, "[]") {
			return tsType(gnoType[2:]) + "[]"
		}
		return "any"
	}
}

// tsCamel lower-camel-cases an identifier.
func tsCamel(name string) string {
	if name == "" {
		return name
	}
	return strings.ToLower(name[:1]) + name[1:]
}

// tsPascal upper-camel-cases an identifier for generated type names.
func tsPascal(name string) string {
	if name == "" {
		return name
	}
	return strings.ToUpper(name[:1]) + name[1:]
}
